    private static PropertyBuilder<string> Key(PropertyBuilder<string> property) => property.HasMaxLength(64);

    private static PropertyBuilder<T> Json<T>(PropertyBuilder<T> property) => property.HasColumnType("jsonb");

    private static PropertyBuilder<TEnum> Enum<TEnum>(PropertyBuilder<TEnum> property, int maxLength = 16) =>
        property.HasConversion<string>().HasMaxLength(maxLength);

    /// <summary>
    /// Maps the PostgreSQL <c>xmin</c> system column (optimistic concurrency; never created by migrations). Not used on
    /// partitioned tables: PostgreSQL cannot return system columns from them.
    /// </summary>
    private static void RowVersion(PropertyBuilder<uint> property) => property.IsRowVersion().HasColumnName("xmin");

    private static void Authorship<T>(EntityTypeBuilder<T> entity)
        where T : class
    {
        entity.Property<string>("CreatedBy").HasMaxLength(200);
        entity.Property<string>("UpdatedBy").HasMaxLength(200);
    }

    private static void Check<T>(TableBuilder<T> table, string column, Type enumType)
        where T : class
    {
        var values = string.Join(", ", System.Enum.GetNames(enumType).Select(n => $"'{n}'"));
        table.HasCheckConstraint($"ck_{table.Name}_{column}", $"{column} IN ({values})");
    }

    /// <summary>Tables, columns, keys and indexes in snake_case (explicit names are kept).</summary>
    private static void ApplySnakeCase(ModelBuilder model)
    {
        foreach (var entity in model.Model.GetEntityTypes())
        {
            var table = StoreObjectIdentifier.Table(entity.GetTableName()!, entity.GetSchema());
            foreach (var property in entity.GetProperties())
            {
                if (property.GetColumnName(table) == property.Name)
                {
                    property.SetColumnName(SnakeCase(property.Name));
                }
            }

            foreach (var key in entity.GetKeys())
            {
                key.SetName(key.IsPrimaryKey() ? $"pk_{entity.GetTableName()}" : $"ak_{entity.GetTableName()}_{Columns(key.Properties)}");
            }

            foreach (var foreignKey in entity.GetForeignKeys())
            {
                foreignKey.SetConstraintName($"fk_{entity.GetTableName()}_{foreignKey.PrincipalEntityType.GetTableName()}_{Columns(foreignKey.Properties)}");
            }

            foreach (var index in entity.GetIndexes().Where(i => i.FindAnnotation(RelationalAnnotationNames.Name) is null))
            {
                index.SetDatabaseName($"{(index.IsUnique ? "ux" : "ix")}_{entity.GetTableName()}_{Columns(index.Properties)}");
            }
        }
    }

    private static string Columns(IReadOnlyList<IReadOnlyProperty> properties) => string.Join("_", properties.Select(p => SnakeCase(p.Name)));

    private static string SnakeCase(string name)
    {
        var builder = new StringBuilder(name.Length + 8);
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsUpper(c))
            {
                if (i > 0 && (char.IsLower(name[i - 1]) || (i + 1 < name.Length && char.IsLower(name[i + 1]))))
                {
                    builder.Append('_');
                }

                builder.Append(char.ToLowerInvariant(c));
            }
            else
            {
                builder.Append(c);
            }
        }

        return builder.ToString();
    }
