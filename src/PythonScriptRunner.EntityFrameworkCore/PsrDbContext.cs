using System.Text;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using PythonScriptRunner.EntityFrameworkCore.Entities;

namespace PythonScriptRunner.EntityFrameworkCore;

/// <summary>
/// Database of PythonScriptRunner (schema <c>psr</c>). Advanced API: the queue, worker and dashboard packages use it to
/// write in the same transaction as their own changes.
/// </summary>
/// <param name="options">Context options.</param>
public sealed class PsrDbContext(DbContextOptions<PsrDbContext> options) : DbContext(options)
{
    /// <summary>Dedicated schema of every table.</summary>
    public const string Schema = "psr";

    /// <summary>Table that records the applied migrations.</summary>
    public const string MigrationsHistoryTable = "__ef_migrations_history";

#pragma warning disable CS1591 // One set per table of the documented schema.
    public DbSet<StageEntity> Stages => Set<StageEntity>();

    public DbSet<StageVersionEntity> StageVersions => Set<StageVersionEntity>();

    public DbSet<PipelineEntity> Pipelines => Set<PipelineEntity>();

    public DbSet<PipelineVersionEntity> PipelineVersions => Set<PipelineVersionEntity>();

    public DbSet<PipelineStepEntity> PipelineSteps => Set<PipelineStepEntity>();

    public DbSet<ScheduleEntity> Schedules => Set<ScheduleEntity>();

    public DbSet<RunEntity> Runs => Set<RunEntity>();

    public DbSet<StepRunEntity> StepRuns => Set<StepRunEntity>();

    public DbSet<StepAttemptEntity> StepAttempts => Set<StepAttemptEntity>();

    public DbSet<AttemptLogEntity> AttemptLogs => Set<AttemptLogEntity>();

    public DbSet<ArtifactEntity> Artifacts => Set<ArtifactEntity>();

    public DbSet<ArtifactContentEntity> ArtifactContents => Set<ArtifactContentEntity>();

    public DbSet<OutboxMessageEntity> OutboxMessages => Set<OutboxMessageEntity>();

    public DbSet<IdempotencyKeyEntity> IdempotencyKeys => Set<IdempotencyKeyEntity>();

    public DbSet<AuditEventEntity> AuditEvents => Set<AuditEventEntity>();
#pragma warning restore CS1591

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema(Schema);
        ConfigureCatalog(modelBuilder);
        ConfigureRuns(modelBuilder);
        ConfigureInfrastructure(modelBuilder);
        ApplySnakeCase(modelBuilder);

        // Identifiers are UUID v7 generated by the application: new rows reached through navigations are inserted.
        foreach (var key in modelBuilder.Model.GetEntityTypes().SelectMany(e => e.GetKeys()))
        {
            foreach (var property in key.Properties.Where(p => p.ClrType == typeof(Guid)))
            {
                property.ValueGenerated = ValueGenerated.Never;
            }
        }
    }

    private static void ConfigureCatalog(ModelBuilder model)
    {
        model.Entity<StageEntity>(e =>
        {
            e.ToTable("stages");
            Key(e.Property(x => x.Key));
            e.Property(x => x.Name).HasMaxLength(200);
            Authorship(e);
            RowVersion(e.Property(x => x.RowVersion));
            e.HasIndex(x => x.Key).IsUnique();
            e.HasMany(x => x.Versions).WithOne(x => x.Stage).HasForeignKey(x => x.StageId).OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<StageVersionEntity>(e =>
        {
            e.ToTable("stage_versions", t => Check(t, "status", typeof(VersionStatus)));
            Enum(e.Property(x => x.Status)).HasDefaultValue(VersionStatus.Draft);
            e.Property(x => x.ScriptSha256).HasMaxLength(64).IsFixedLength();
            e.Property(x => x.PythonVersion).HasMaxLength(10);
            e.Property(x => x.EnvironmentHash).HasMaxLength(64).IsFixedLength();
            Json(e.Property(x => x.InputFields));
            Json(e.Property(x => x.OutputFields));
            e.Property(x => x.RetryBackoffMultiplier).HasPrecision(4, 2);
            e.Property(x => x.PublishedBy).HasMaxLength(200);
            e.Property(x => x.ArchivedBy).HasMaxLength(200);
            Authorship(e);
            RowVersion(e.Property(x => x.RowVersion));
            e.HasIndex(x => new { x.StageId, x.Version }).IsUnique();
            e.HasIndex(x => x.StageId).IsUnique().HasFilter("status = 'Draft'").HasDatabaseName("ux_stage_versions_draft");
        });

        model.Entity<PipelineEntity>(e =>
        {
            e.ToTable("pipelines");
            Key(e.Property(x => x.Key));
            e.Property(x => x.Name).HasMaxLength(200);
            Authorship(e);
            RowVersion(e.Property(x => x.RowVersion));
            e.HasIndex(x => x.Key).IsUnique();
            e.HasMany(x => x.Versions).WithOne(x => x.Pipeline).HasForeignKey(x => x.PipelineId).OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<PipelineVersionEntity>(e =>
        {
            e.ToTable("pipeline_versions", t => Check(t, "status", typeof(VersionStatus)));
            Enum(e.Property(x => x.Status)).HasDefaultValue(VersionStatus.Draft);
            Json(e.Property(x => x.InputFields));
            Json(e.Property(x => x.Outputs));
            Json(e.Property(x => x.Layout));
            e.Property(x => x.PublishedBy).HasMaxLength(200);
            e.Property(x => x.ArchivedBy).HasMaxLength(200);
            Authorship(e);
            RowVersion(e.Property(x => x.RowVersion));
            e.HasIndex(x => new { x.PipelineId, x.Version }).IsUnique();
            e.HasIndex(x => x.PipelineId).IsUnique().HasFilter("status = 'Draft'").HasDatabaseName("ux_pipeline_versions_draft");
            e.HasMany(x => x.Steps).WithOne().HasForeignKey(x => x.PipelineVersionId).OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<PipelineStepEntity>(e =>
        {
            e.ToTable("pipeline_steps");
            Key(e.Property(x => x.Key));
            e.Property(x => x.DisplayName).HasMaxLength(200);
            Json(e.Property(x => x.Bindings));
            e.HasIndex(x => new { x.PipelineVersionId, x.Order }).IsUnique();
            e.HasIndex(x => new { x.PipelineVersionId, x.Key }).IsUnique();
            e.HasIndex(x => x.StageVersionId);
            e.HasOne(x => x.StageVersion).WithMany().HasForeignKey(x => x.StageVersionId).OnDelete(DeleteBehavior.Restrict);
        });

        model.Entity<ScheduleEntity>(e =>
        {
            e.ToTable("schedules");
            e.Property(x => x.Name).HasMaxLength(200);
            e.Property(x => x.Cron).HasMaxLength(100);
            e.Property(x => x.TimeZone).HasMaxLength(64).HasDefaultValue("America/Sao_Paulo");
            Json(e.Property(x => x.Inputs)).HasDefaultValueSql("'{}'::jsonb");
            e.Property(x => x.IsEnabled).HasDefaultValue(true);
            Authorship(e);
            RowVersion(e.Property(x => x.RowVersion));
            e.HasIndex(x => x.NextRunAt).HasFilter("is_enabled");
            e.HasOne<PipelineEntity>().WithMany().HasForeignKey(x => x.PipelineId).OnDelete(DeleteBehavior.Cascade);
        });
    }

