            e.HasKey(x => new { x.Id, x.CreatedAt });
            Enum(e.Property(x => x.Kind));
            Enum(e.Property(x => x.Mode), 8);
            Enum(e.Property(x => x.Trigger));
            Enum(e.Property(x => x.Status));
            e.Property(x => x.PipelineKey).HasMaxLength(64);
            e.Property(x => x.StageKey).HasMaxLength(64);
            e.Property(x => x.TriggeredBy).HasMaxLength(200);
            Json(e.Property(x => x.Inputs));
            Json(e.Property(x => x.Outputs));
            Json(e.Property(x => x.Error));
            Json(e.Property(x => x.TriggerDetails));
            e.Property(x => x.IdempotencyKey).HasMaxLength(200);
            e.Property(x => x.CorrelationId).HasMaxLength(200);
            e.Property(x => x.TraceParent).HasMaxLength(55);
