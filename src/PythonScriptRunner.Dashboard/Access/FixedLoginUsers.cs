using System.Security.Cryptography;
using System.Text;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace PythonScriptRunner.Dashboard.Access;

/// <summary>Fixed login settings as bound from configuration (reloaded when it changes).</summary>
internal sealed class FixedLoginSettings
{
    public List<FixedLoginUser> Users { get; set; } = [];

    public TimeSpan SlidingExpiration { get; set; } = TimeSpan.FromHours(8);

    public TimeSpan AbsoluteExpiration { get; set; } = TimeSpan.FromHours(24);

    public int MaxFailedAttempts { get; set; } = 5;

    public TimeSpan LockoutDuration { get; set; } = TimeSpan.FromMinutes(15);

    public int MaxAttemptsPerMinutePerIp { get; set; } = 10;
}

/// <summary>A validated user of the fixed login.</summary>
/// <param name="Name">User name as configured.</param>
/// <param name="Role">Role.</param>
/// <param name="PasswordHash">Password hash.</param>
/// <param name="Stamp">Fingerprint of the hash kept in the session: a changed password ends the sessions.</param>
internal sealed record LoginAccount(string Name, DashboardRole Role, string PasswordHash, string Stamp);

/// <summary>
/// The current users of the fixed login (D-119, D-128). A reloaded configuration replaces them only when valid; an invalid one
/// is refused and logged, and the previous users stay.
/// </summary>
internal sealed partial class FixedLoginUsers : IDisposable
{
    private readonly ILogger<FixedLoginUsers> _logger;
    private readonly IDisposable? _subscription;
    private volatile Snapshot _current;

    public FixedLoginUsers(IOptionsMonitor<FixedLoginSettings> settings, ILogger<FixedLoginUsers> logger)
    {
        _logger = logger;
        _current = Validate(settings.CurrentValue) is { } first
            ? first
            : throw new PsrConfigurationException(
                $"Invalid fixed login configuration of the dashboard: {string.Join("; ", Errors(settings.CurrentValue))}. Configure the users in code or "
                + $"in the section {FixedLoginOptions.DefaultSection} (e.g. PythonScriptRunner__Dashboard__Login__Users__0__Name, __Role and "
                + "__PasswordHash, with the hash generated by 'psr hash-password').");
        _subscription = settings.OnChange(changed =>
        {
            if (Validate(changed) is { } next)
            {
                _current = next;
            }
            else
            {
                LogReloadRefused(_logger);
            }
        });
    }

    /// <summary>Current settings (session and lockout).</summary>
    public FixedLoginSettings Settings => _current.Settings;

    /// <summary>Finds a user by name (ignoring case).</summary>
    public LoginAccount? Find(string? name) => name is not null && _current.Accounts.TryGetValue(name, out var account) ? account : null;

    public void Dispose() => _subscription?.Dispose();

    /// <summary>Problems of a configuration (empty when it is valid).</summary>
    public static IReadOnlyList<string> Errors(FixedLoginSettings settings)
    {
        var errors = new List<string>();
        if (settings.Users.Count == 0)
        {
            errors.Add("no users are configured");
        }

        foreach (var user in settings.Users)
        {
            var name = string.IsNullOrWhiteSpace(user.Name) ? "(empty name)" : user.Name;
            if (string.IsNullOrWhiteSpace(user.Name) || user.Name.Length > 100)
            {
                errors.Add($"user '{name}': the name must have 1-100 chars");
            }

            if (!Enum.IsDefined(user.Role))
            {
                errors.Add($"user '{name}': unknown role");
            }

            if (!DashboardPasswords.IsHash(user.PasswordHash))
            {
                errors.Add($"user '{name}': PasswordHash is not a hash generated by 'psr hash-password' (plain passwords are not accepted)");
            }
        }

        errors.AddRange(settings.Users.Where(u => !string.IsNullOrWhiteSpace(u.Name))
            .GroupBy(u => u.Name, StringComparer.OrdinalIgnoreCase).Where(g => g.Count() > 1)
            .Select(g => $"user '{g.Key}' is configured more than once"));
        if (settings.SlidingExpiration <= TimeSpan.Zero || settings.AbsoluteExpiration < settings.SlidingExpiration)
        {
            errors.Add("SlidingExpiration must be positive and not longer than AbsoluteExpiration");
        }

        if (settings.MaxFailedAttempts < 1 || settings.LockoutDuration <= TimeSpan.Zero || settings.MaxAttemptsPerMinutePerIp < 1)
        {
            errors.Add("MaxFailedAttempts, LockoutDuration and MaxAttemptsPerMinutePerIp must be positive");
        }

        return errors;
    }

    /// <summary>Stamp of a hash (SHA-256, first 16 hex chars).</summary>
    public static string StampOf(string passwordHash) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(passwordHash)))[..16];

    private Snapshot? Validate(FixedLoginSettings settings)
    {
        var errors = Errors(settings);
        if (errors.Count > 0)
        {
            LogInvalid(_logger, string.Join("; ", errors));
            return null;
        }

        return new Snapshot(settings, settings.Users.ToDictionary(
            u => u.Name,
            u => new LoginAccount(u.Name, u.Role, u.PasswordHash, StampOf(u.PasswordHash)),
            StringComparer.OrdinalIgnoreCase));
    }

    [LoggerMessage(300, LogLevel.Error, "Invalid fixed login configuration of the dashboard: {Errors}")]
    private static partial void LogInvalid(ILogger logger, string errors);

    [LoggerMessage(301, LogLevel.Error, "The changed fixed login configuration was refused; the previous users stay valid")]
    private static partial void LogReloadRefused(ILogger logger);

    private sealed record Snapshot(FixedLoginSettings Settings, IReadOnlyDictionary<string, LoginAccount> Accounts);
}
